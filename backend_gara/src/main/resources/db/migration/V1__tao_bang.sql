CREATE TABLE tblUser (
    userID   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    fullname varchar(255) NOT NULL,
    phone    varchar(15)  NOT NULL,
    email    varchar(255) NOT NULL
);

CREATE TABLE tblCustomer (
    userID  integer PRIMARY KEY REFERENCES tblUser (userID),
    address varchar(255) NOT NULL
);

CREATE TABLE tblManager (
    userID         integer PRIMARY KEY REFERENCES tblUser (userID),
    employeeCode   varchar(20)  NOT NULL,
    specialization varchar(255) NOT NULL
);

CREATE TABLE tblStaff (
    userID         integer PRIMARY KEY REFERENCES tblUser (userID),
    employeeCode   varchar(20)  NOT NULL,
    specialization varchar(255) NOT NULL,
    bankAccount    varchar(30)  NOT NULL
);

CREATE TABLE tblCar (
    carID        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customerID   integer     NOT NULL REFERENCES tblCustomer (userID),
    licensePlate varchar(15) NOT NULL,
    brand        varchar(50) NOT NULL,
    model        varchar(50) NOT NULL,
    year         integer     NOT NULL
);

CREATE TABLE tblAppointment (
    appointmentID integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customerID    integer     NOT NULL REFERENCES tblCustomer (userID),
    time          timestamp   NOT NULL,
    status        varchar(30) NOT NULL
);

CREATE TABLE tblAppointmentDetail (
    appointmentDetailID integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointmentID       integer NOT NULL REFERENCES tblAppointment (appointmentID),
    carID               integer NOT NULL REFERENCES tblCar (carID)
);

CREATE TABLE tblSlot (
    slotID   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location varchar(50) NOT NULL,
    status   varchar(30) NOT NULL
);

CREATE TABLE tblServiceSlip (
    serviceSlipID       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointmentDetailID integer NOT NULL UNIQUE REFERENCES tblAppointmentDetail (appointmentDetailID),
    slotID              integer REFERENCES tblSlot (slotID),
    time                timestamp   NOT NULL,
    status              varchar(30) NOT NULL,
    totalCost           double precision
);

CREATE TABLE tblSlipHandling (
    serviceSlipID integer     NOT NULL REFERENCES tblServiceSlip (serviceSlipID),
    managerID     integer     NOT NULL REFERENCES tblManager (userID),
    role          varchar(30) NOT NULL,
    handledAt     timestamp,
    PRIMARY KEY (serviceSlipID, managerID, role)
);

CREATE TABLE tblService (
    serviceID    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(255)     NOT NULL,
    price        double precision NOT NULL,
    laborContent double precision NOT NULL
);

CREATE TABLE tblServiceDetail (
    serviceSlipID integer          NOT NULL REFERENCES tblServiceSlip (serviceSlipID),
    serviceID     integer          NOT NULL REFERENCES tblService (serviceID),
    staffID       integer          REFERENCES tblStaff (userID),
    price         double precision NOT NULL,
    laborContent  double precision NOT NULL,
    startedAt     timestamp,
    finishedAt    timestamp,
    PRIMARY KEY (serviceSlipID, serviceID)
);

CREATE TABLE tblComponent (
    componentID  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(255)     NOT NULL,
    price        double precision NOT NULL,
    inventoryQty integer          NOT NULL
);

CREATE TABLE tblComponentDetail (
    serviceSlipID integer          NOT NULL REFERENCES tblServiceSlip (serviceSlipID),
    componentID   integer          NOT NULL REFERENCES tblComponent (componentID),
    qty           integer          NOT NULL,
    price         double precision NOT NULL,
    PRIMARY KEY (serviceSlipID, componentID)
);

CREATE TABLE tblSalaryTable (
    salaryTableID  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staffID        integer          NOT NULL REFERENCES tblStaff (userID),
    managerID      integer          NOT NULL REFERENCES tblManager (userID),
    month          integer          NOT NULL,
    year           integer          NOT NULL,
    laborUnitPrice double precision NOT NULL,
    paymentMethod  varchar(30),
    isReceived     boolean          NOT NULL,
    status         varchar(30)      NOT NULL
);
